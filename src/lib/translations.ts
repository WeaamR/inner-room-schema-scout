export function localizedField(row: object, englishKey: string, arabicKey: string, language: Language): string {
  const record = row as Record<string, unknown>;
  const key = language === "ar" ? arabicKey : englishKey;
  const value = record[key];
  return typeof value === "string" && value.trim() ? value : translate(language, "الترجمة غير متاحة");
}
export function reportMissingTranslations(rows: object[], pairs: [string, string][]) {
  for (const row of rows) for (const pair of pairs) for (const field of pair) {
    const record = row as Record<string, unknown>;
    if (typeof record[field] !== "string" || !(record[field] as string).trim()) console.warn("Missing saved translation", { id: record["id"], field });
  }
}
